"""Neighbourhood profiles with provenance — the data model behind Lifestyle Match.

The unit is the LOR *Bezirksregion* (143 regions covering all of Berlin; ADR-0010):
the official level at which both the police crime atlas and the population register
can be joined without estimation. Every number carries where it came from:

    Measure(raw=2175.3, unit="offences per 100,000 residents",
            source_id="pks_kriminalitaetsatlas", year="2023–2025", method="…")

Normalisation to a 0..1 score uses *fixed* reference points stored in the bundle
(continuous measures: 10th/90th percentile across all Berlin regions, computed once at
build time; class-based measures: the class bounds 1..3) — never
re-derived from whichever regions happen to be in a result list. So removing or
filtering regions can't change any other region's score, and a score means the same
thing in every request.

The bundle is generated by `data/lifestyle/build_profiles.py` and validated on load;
an inconsistent file (unknown source, unknown attribute, missing reference range)
fails loudly rather than scoring on bad data.
"""

from __future__ import annotations

import math
from functools import lru_cache
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, Field, model_validator

from lifestyle.attributes import ATTRIBUTES, ATTRIBUTES_BY_ID, Attribute

BUNDLE_PATH = Path(__file__).resolve().parents[1] / "data" / "lifestyle" / "regions.json"
SCHEMA_VERSION = 1


class Source(BaseModel):
    id: str
    title: str
    publisher: str
    url: str | None = None
    licence: str | None = None  # None = not stated by the publisher
    data_year: str  # period the figures describe, e.g. "2025" or "2023–2025"
    used_for: str  # which figures we take from it
    caveat: str | None = None  # shown next to the number in the UI


class Measure(BaseModel):
    raw: float
    unit: str
    source_id: str
    year: str
    method: str  # how the raw value was derived from the source
    # For class-based indicators: % of residents in each class
    # ({"best": 62.1, "middle": 30.0, "worst": 7.9}), which explains a mean class in
    # words ("62% of residents live in planning areas in Berlin's quietest class").
    shares: dict[str, float] | None = None


class CityFigure(BaseModel):
    """A Berlin-wide number (e.g. median asking rent) with its provenance."""

    value: float
    unit: str
    source_id: str
    year: str
    note: str | None = None


class Reference(BaseModel):
    """Fixed normalisation range for one attribute (raw units)."""

    low: float  # continuous: 10th percentile across Berlin regions; classes: 1 (best)
    high: float  # continuous: 90th percentile; classes: 3 (worst)
    berlin: float  # Berlin-wide value, for "vs. Berlin average" explanations
    unit: str
    method: str  # how low/high were fixed, shown in "how scoring works"
    # "log" for counts (2 → 10 cafés matters more than 100 → 130), else linear.
    scale: Literal["linear", "log"] = "linear"

    @model_validator(mode="after")
    def _ordered(self) -> Reference:
        if not self.low < self.high:
            raise ValueError(f"reference low ({self.low}) must be < high ({self.high})")
        return self


class Region(BaseModel):
    key: str = Field(pattern=r"^\d{6}$")  # LOR Bezirksregion key: Bezirk+Prognoseraum+BZR
    name: str
    district: str
    population: int = Field(ge=0)
    # One of data.kieze.KIEZE when the region lies in that Ortsteil — used to hand off
    # to WohnIQ listings. None = no listings in our (synthetic) inventory there.
    listing_kiez: str | None = None
    # Population-weighted centre (lat, lng) — where people live; used for commute.
    centroid: tuple[float, float] | None = None
    geo_source_id: str | None = None  # source of centroid / area / inner-city share
    area_km2: float | None = None
    density_per_km2: int | None = None
    # Share of residents living in planning areas the Senate classifies "Innere Stadt".
    inner_city_share: float | None = Field(default=None, ge=0, le=1)
    # Median asking rent (EUR/m² net cold) of the region's district; see build_profiles.
    rent: Measure | None = None
    # Range (EUR/m²) that 80% of the district's offers fall into, to show the spread.
    rent_range: tuple[float, float] | None = None
    measures: dict[str, Measure] = Field(default_factory=dict)


class Destination(BaseModel):
    """A fixed commute destination (v1 offers a curated list, never free text)."""

    id: str
    name: str
    short: str
    kind: Literal["university", "hub"]
    lat: float
    lng: float
    derived_from: str  # where the coordinates come from (OSM feature / VBB stop)


class CommuteTime(BaseModel):
    minutes: int = Field(ge=0)
    changes: int | None = None
    source: Literal["network", "distance"]  # VBB timetable route, or straight-line fallback


class CommuteInfo(BaseModel):
    """Precomputed public-transport times: destination id -> region key -> time."""

    method: str
    source_id: str
    times: dict[str, dict[str, CommuteTime]]


class ProfileBundle(BaseModel):
    schema_version: int
    inputs: dict[str, str] = Field(default_factory=dict)  # raw file name -> sha256
    sources: dict[str, Source]
    city: dict[str, CityFigure] = Field(default_factory=dict)
    references: dict[str, Reference]
    regions: list[Region]
    destinations: list[Destination] = Field(default_factory=list)
    commute: CommuteInfo | None = None

    @model_validator(mode="after")
    def _consistent(self) -> ProfileBundle:
        if self.schema_version != SCHEMA_VERSION:
            raise ValueError(f"schema_version {self.schema_version} != {SCHEMA_VERSION}")
        for ref_id in self.references:
            if ref_id not in ATTRIBUTES_BY_ID:
                raise ValueError(f"reference for unknown attribute {ref_id!r}")
        for fig_id, fig in self.city.items():
            if fig.source_id not in self.sources:
                raise ValueError(f"city figure {fig_id!r} cites unknown source {fig.source_id!r}")
        keys: set[str] = set()
        for region in self.regions:
            if region.key in keys:
                raise ValueError(f"duplicate region key {region.key}")
            keys.add(region.key)
            if region.rent is not None and region.rent.source_id not in self.sources:
                raise ValueError(f"{region.key}: rent cites unknown source")
            if region.centroid is not None and region.geo_source_id not in self.sources:
                raise ValueError(f"{region.key}: geography cites unknown source")
            for attr_id, measure in region.measures.items():
                if attr_id not in ATTRIBUTES_BY_ID:
                    raise ValueError(f"{region.key}: unknown attribute {attr_id!r}")
                if attr_id not in self.references:
                    raise ValueError(f"{region.key}: {attr_id!r} has no reference range")
                if measure.source_id not in self.sources:
                    raise ValueError(
                        f"{region.key}: {attr_id!r} cites unknown source {measure.source_id!r}"
                    )
        if self.commute is not None:
            if self.commute.source_id not in self.sources:
                raise ValueError("commute cites unknown source")
            dest_ids = {d.id for d in self.destinations}
            if set(self.commute.times) != dest_ids:
                raise ValueError("commute times don't match the destination list")
            for dest_id, by_region in self.commute.times.items():
                if set(by_region) != keys:
                    raise ValueError(f"commute times to {dest_id!r} don't cover every region")
        return self

    # --- Queries -------------------------------------------------------------------

    def region(self, key: str) -> Region | None:
        return next((r for r in self.regions if r.key == key), None)

    def destination(self, dest_id: str) -> Destination | None:
        return next((d for d in self.destinations if d.id == dest_id), None)

    def commute_time(self, dest_id: str, region_key: str) -> CommuteTime | None:
        if self.commute is None:
            return None
        return self.commute.times.get(dest_id, {}).get(region_key)

    def available_attributes(self) -> list[Attribute]:
        """Area attributes we hold data for, in catalogue order."""
        return [a for a in ATTRIBUTES if a.kind == "area" and a.id in self.references]

    def pending_attributes(self) -> list[Attribute]:
        """Area attributes in the catalogue whose data hasn't been built yet."""
        return [a for a in ATTRIBUTES if a.kind == "area" and a.id not in self.references]

    def score(self, attribute_id: str, raw: float) -> float:
        """Normalise a raw measure to 0..1, where 1 = best fit for this attribute."""
        attr = ATTRIBUTES_BY_ID[attribute_id]
        ref = self.references[attribute_id]
        if ref.scale == "log":
            low, high, value = math.log1p(ref.low), math.log1p(ref.high), math.log1p(raw)
        else:
            low, high, value = ref.low, ref.high, raw
        position = (value - low) / (high - low)
        position = max(0.0, min(1.0, position))
        return position if attr.higher_is_better else 1.0 - position


def load_bundle(path: Path = BUNDLE_PATH) -> ProfileBundle:
    return ProfileBundle.model_validate_json(path.read_text(encoding="utf-8"))


@lru_cache(maxsize=1)
def get_bundle() -> ProfileBundle:
    """The shipped bundle, parsed and validated once per process."""
    return load_bundle()
